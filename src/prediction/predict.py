import os
import json
import datetime
import pandas as pd
from pyspark.sql import SparkSession
from pyspark.sql.functions import col, lit, current_timestamp, coalesce
from pyspark.ml import PipelineModel

def create_spark_session():
    """Create and return a SparkSession."""
    java_home_adoptium = r"C:\Program Files\Eclipse Adoptium\jre-25.0.1.8-hotspot"
    if os.path.exists(java_home_adoptium):
        os.environ["JAVA_HOME"] = java_home_adoptium
        os.environ["PATH"] = os.path.join(java_home_adoptium, "bin") + os.pathsep + os.environ.get("PATH", "")

    return SparkSession.builder \
        .appName("AirlineDelayPredictionEngine") \
        .config("spark.sql.shuffle.partitions", "10") \
        .getOrCreate()

def run_predictions(spark, feature_path=None, reg_model_path=None, clf_model_path=None):
    """
    Loads saved best regression and classification models, computes predictions
    on test/future records, and exports formatted results.
    """
    if feature_path is None:
        if os.path.exists("data/features/airline_features.parquet"):
            feature_path = "data/features/airline_features.parquet"
        else:
            feature_path = "hdfs:///data/airline/features/airline_features.parquet"

    if reg_model_path is None:
        reg_model_path = "data/models/regression/best_regression_model"

    if clf_model_path is None:
        clf_model_path = "data/models/classification/best_classification_model"

    print(f"Loading feature dataset from: {feature_path}")
    df_features = spark.read.parquet(feature_path)

    # Filter to most recent year/month observation per carrier-airport combination for future predictions
    latest_year = df_features.agg({"year": "max"}).collect()[0][0]
    latest_features = df_features.filter(col("year") == latest_year)
    print(f"Predicting for latest dataset year {latest_year} ({latest_features.count()} records)...")

    # Load Models
    reg_model_name = "Best Regression Model"
    clf_model_name = "Best Classification Model"

    if os.path.exists(os.path.join("data/models/regression", "metadata.json")):
        with open(os.path.join("data/models/regression", "metadata.json"), "r") as f:
            reg_meta = json.load(f)
            reg_model_name = reg_meta.get("best_model_name", reg_model_name)

    if os.path.exists(os.path.join("data/models/classification", "metadata.json")):
        with open(os.path.join("data/models/classification", "metadata.json"), "r") as f:
            clf_meta = json.load(f)
            clf_model_name = clf_meta.get("best_model_name", clf_model_name)

    print(f"Loading regression model from: {reg_model_path}")
    reg_model = PipelineModel.load(reg_model_path)
    reg_preds = reg_model.transform(latest_features)

    # Rename prediction column from regression model
    reg_preds = reg_preds.withColumnRenamed("prediction", "predicted_delay_rate")

    # Drop intermediate pipeline columns generated by regression model before applying classification model
    cols_to_drop = [
        "carrier_indexed", "airport_indexed",
        "carrier_encoded", "airport_encoded",
        "features_assembled", "features",
        "rawPrediction", "probability"
    ]
    clf_input = reg_preds.drop(*[c for c in cols_to_drop if c in reg_preds.columns])

    print(f"Loading classification model from: {clf_model_path}")
    clf_model = PipelineModel.load(clf_model_path)
    final_preds = clf_model.transform(clf_input)
    final_preds = final_preds.withColumnRenamed("prediction", "predicted_high_delay")

    # Target calendar prediction month formatting
    final_preds = final_preds.withColumn("prediction_year", when_next_year(col("year"), col("month"))) \
                             .withColumn("prediction_month", when_next_month(col("month"))) \
                             .withColumn("actual_delay_rate", col("next_month_delay_rate")) \
                             .withColumn("model_name", lit(reg_model_name)) \
                             .withColumn("model_version", lit("1.0.0")) \
                             .withColumn("prediction_timestamp", current_timestamp())

    select_cols = [
        "carrier", "carrier_name", "airport", "airport_name",
        "prediction_year", "prediction_month", "actual_delay_rate",
        "predicted_delay_rate", "predicted_high_delay",
        "model_name", "model_version", "prediction_timestamp"
    ]
    # Filter available columns
    existing_cols = [c for c in select_cols if c in final_preds.columns]
    output_df = final_preds.select(*existing_cols)

    # Export locally to CSV & Parquet
    os.makedirs("output/predictions", exist_ok=True)
    os.makedirs("data/predictions", exist_ok=True)

    pdf = output_df.toPandas()
    csv_path = "output/predictions/predictions.csv"
    pdf.to_csv(csv_path, index=False)
    print(f"Saved predictions CSV to: {csv_path}")

    parquet_path = "data/predictions/delay_predictions.parquet"
    output_df.write.mode("overwrite").parquet(parquet_path)
    print(f"Saved predictions Parquet to: {parquet_path}")

    print("Prediction pipeline completed successfully.")
    return pdf

def when_next_year(year_col, month_col):
    return col("year") + (col("month") == 12).cast("integer")

def when_next_month(month_col):
    return (col("month") % 12) + 1

if __name__ == "__main__":
    spark = create_spark_session()
    run_predictions(spark)
    spark.stop()
